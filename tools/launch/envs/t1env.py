#!/usr/bin/env python3
"""Window 1 (T1) env generator: turn a saved TP4 mesh serve env (C) into per-rank --shape hybrid envs.

    t1env.py C.env --home NEW_G6_HOME --control-port P [--deny 0-2,1-3] [--prefix 24] --out DIR

Writes DIR/cluster-t1.env.r<N> for each rank N. Each file is C with:
  SHAPE=hybrid, G6_HOME=NEW_G6_HOME (the staged test tree, not the serve tree),
  IPS and IPS2 removed, FAB_PORTS=IPS[N]/prefix,IPS2[N]/prefix (IPS first, so the canonical rail order is C's: T1a
  has C's rail layout), CONTROL_PORT=P, FAB_DENY when given.
Everything else (MODEL, PEERS, PORT, G6ENV_X, steering, knobs, comments) is copied verbatim, so the byte oracle runs
C's config. Prints the route table sha that every rank must log. No real value lives in this repo: C is an input.
"""
import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import options  # noqa: E402
import routes  # noqa: E402

DROP = ('IPS', 'IPS2')
SET = ('SHAPE', 'G6_HOME', 'CONTROL_PORT', 'FAB_PORTS', 'FAB_DENY')


def generate(src, home, control_port, deny='', prefix=24):
    """Returns ([text per rank], routes sha). Raises ValueError naming the problem."""
    c = options.parse_file(src)
    for k in ('PEERS', 'IPS', 'IPS2'):
        if not c.get(k):
            raise ValueError(f'{src}: no {k}: T1 derives FAB_PORTS from C\'s IPS and IPS2')
    peers, ips, ips2 = (options.split_list(c[k]) for k in ('PEERS', 'IPS', 'IPS2'))
    if not len(peers) == len(ips) == len(ips2):
        raise ValueError(f'{src}: PEERS, IPS and IPS2 differ in length ({len(peers)}, {len(ips)}, {len(ips2)})')
    if c.get('TP') and int(c['TP']) != len(peers):
        raise ValueError(f'{src}: TP={c["TP"]} but {len(peers)} peers')
    old = int(c.get('CONTROL_PORT') or options.SERVE_CONTROL_PORT)
    if control_port in (old, int(options.SERVE_CONTROL_PORT)):
        raise ValueError(f'--control-port {control_port}: that is the serves\' control port; T1 needs its own')
    ports = [f'{a}/{prefix},{b}/{prefix}' for a, b in zip(ips, ips2)]
    try:
        table = routes.compute(ports, routes.parse_deny(deny, len(peers)), names=peers)
    except routes.RouteError as e:
        raise ValueError(f'routes: {e}')
    with open(src) as f:
        lines = f.read().splitlines()
    keep = []
    for line in lines:
        m = re.match(r'\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)=', line)
        if m and (m.group(1) in DROP or m.group(1) in SET):
            continue
        keep.append(line)
    out = []
    for r in range(len(peers)):
        head = [f'# T1 hybrid env, rank {r}: generated by tools/launch/envs/t1env.py from {os.path.basename(src)}',
                f'# routes sha {table.sha}']
        tail = ['SHAPE=hybrid', f'G6_HOME={home}', f'CONTROL_PORT={control_port}', f'FAB_PORTS={ports[r]}']
        if deny:
            tail.append(f'FAB_DENY={deny}')
        out.append('\n'.join(head + keep + tail) + '\n')
    return out, table.sha


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('src')
    ap.add_argument('--home', required=True)
    ap.add_argument('--control-port', type=int, required=True)
    ap.add_argument('--deny', default='')
    ap.add_argument('--prefix', type=int, default=24)
    ap.add_argument('--out', required=True)
    a = ap.parse_args(argv)
    if not os.path.isabs(a.home):
        print('t1env: --home must be an absolute path on the boxes', file=sys.stderr)
        return 2
    try:
        texts, sha = generate(a.src, a.home, a.control_port, a.deny, a.prefix)
    except (ValueError, options.OptionError) as e:
        print(f't1env: {e}', file=sys.stderr)
        return 2
    os.makedirs(a.out, exist_ok=True)
    for r, t in enumerate(texts):
        with open(os.path.join(a.out, f'cluster-t1.env.r{r}'), 'w') as f:
            f.write(t)
    for r in range(len(texts)):   # the launcher's own hybrid checks, on the files as written
        path = os.path.join(a.out, f'cluster-t1.env.r{r}')
        try:
            options.validate_hybrid(options.parse(['@' + path], environ={}), len(texts))
        except options.OptionError as e:
            print(f't1env: {path}: {e}', file=sys.stderr)
            return 2
    print(f'wrote {len(texts)} files to {a.out}')
    print(f'routes sha {sha}')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
