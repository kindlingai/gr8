#!/usr/bin/env python3
"""Engram generator + oracle vectors. Uses the official reference (MIT) as the source of every constant.

  gen_engram.py --ref <ref-official> --tok <tokenizer.json> --out-h engine/engram/hash_consts.h \
                --out-cmap <PREFIX>.engram.cmap [--vectors tests/vectors.bin]

Outputs
  hash_consts.h   multipliers, primes, offsets, table rows, pad id, vocab sizes (checked in; never recomputed at run time)
  *.engram.cmap   "G6ECMAP1" | u32 vocab | u32 cvocab | u32 pad_id | u32 reserved | u32 map[vocab]   (little endian)
                  not checked in (516 KB); its sha256 goes into hash_consts.h so a boot can fail closed on a wrong file
  vectors.bin     official NgramHashState ids for random + hand-made token sequences, read by tests/test_hash.cpp
"""
import argparse, hashlib, json, os, struct, sys
from types import SimpleNamespace

import numpy as np


class TokShim:
    """build_compressed_token_map wants `.backend_tokenizer` and `len()`: the raw Rust tokenizer, as the reference uses it."""

    def __init__(self, path):
        from tokenizers import Tokenizer
        self.backend_tokenizer = Tokenizer.from_file(path)

    def __len__(self):
        return self.backend_tokenizer.get_vocab_size(with_added_tokens=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ref", required=True, help="ref-official dir (holds inference/config.json and inference/engram.py)")
    ap.add_argument("--tok", required=True)
    ap.add_argument("--out-h", required=True)
    ap.add_argument("--out-cmap", required=True)
    ap.add_argument("--vectors", default=None)
    a = ap.parse_args()

    sys.path.insert(0, os.path.join(a.ref, "inference"))
    import torch
    import engram as E  # the official reference

    cfg = json.load(open(os.path.join(a.ref, "inference", "config.json")))
    args = SimpleNamespace(
        engram_layer_ids=cfg["engram_layer_ids"], engram_vocab_size=cfg["engram_vocab_size"],
        engram_num_embeddings=cfg["engram_num_embeddings"], engram_max_ngram_size=cfg["engram_max_ngram_size"],
        engram_pad_id=cfg["engram_pad_id"], engram_compressed_vocab_size=cfg["engram_compressed_vocab_size"],
        engram_n_heads=cfg["engram_n_heads"], engram_head_dim=cfg["engram_head_dim"],
        max_batch_size=1, max_seq_len=4096)
    tok = TokShim(a.tok)
    layout = E.EngramLayout.from_args(args)
    state = E.NgramHashState(args, layout, tok)  # asserts compressed vocab == 99092
    cmap = state.token_map.numpy().astype(np.uint32)
    assert len(cmap) == len(tok) == 129280, len(cmap)
    cvocab = int(cmap.max()) + 1
    assert cvocab == cfg["engram_compressed_vocab_size"] == 99092, cvocab
    pad_id = int(cmap[cfg["engram_pad_id"]])
    primes = state.primes.numpy().astype(np.int64)        # [layer][3][8]
    offsets = state.offsets.numpy().astype(np.int64)      # [layer][24]
    mult = state.multipliers.numpy().astype(np.int64)     # [layer][4]
    nl = len(args.engram_layer_ids)
    assert primes.shape == (nl, 3, 8) and offsets.shape == (nl, 24) and mult.shape == (nl, 4)
    rows = [int(primes[e].sum()) for e in range(nl)]
    assert rows == args.engram_num_embeddings, (rows, args.engram_num_embeddings)
    assert int(primes.max()) < 2**32 and int(offsets.max()) + int(primes.max()) <= 2**32
    assert int(mult.max()) * cvocab < 2**63  # token * multiplier cannot overflow int64

    # --- cmap file
    body = struct.pack("<8sIIII", b"G6ECMAP1", len(cmap), cvocab, pad_id, 0) + cmap.astype("<u4").tobytes()
    open(a.out_cmap, "wb").write(body)
    sha = hashlib.sha256(body).hexdigest()

    # --- constants header
    def arr(x):
        return "{" + ", ".join(str(int(v)) for v in x) + "}"
    L = []
    L.append("// GENERATED by engine/engram/gen_engram.py from the official reference (ref-official/inference/engram.py + config.json).")
    L.append("// Do not edit. Multipliers: 2*default_rng(10007*layer).integers(0, (INT64_MAX/cvocab)/2, 4)+1. Primes: per layer, per n (2..4),")
    L.append("// 8 smallest unused primes > engram_vocab_size - 1, handed out in order. Offsets: exclusive prefix sum of the primes per layer.")
    L.append("#pragma once")
    L.append("#include <cstdint>")
    L.append("#include \"hash.h\"")
    L.append("namespace ds41 { namespace engram {")
    L.append(f"constexpr uint32_t kVocab = {len(cmap)}, kCVocab = {cvocab}, kPadId = {pad_id}, kPadTok = {cfg['engram_pad_id']};")
    L.append(f"constexpr int kLayerIds[kNE] = {arr(args.engram_layer_ids)};")
    L.append(f"constexpr int64_t kRows[kNE] = {arr(rows)};   // = engram_num_embeddings")
    L.append(f"constexpr const char* kCmapSha256 = \"{sha}\";")
    L.append("constexpr HashParams kHashParams = {")
    L.append("    // mult[e][k]")
    L.append("    {" + ", ".join(arr(mult[e]) for e in range(nl)) + "},")
    L.append("    // prime[e][(n-2)*8+h]")
    L.append("    {" + ", ".join(arr(primes[e].reshape(-1)) for e in range(nl)) + "},")
    L.append("    // offset[e][(n-2)*8+h]")
    L.append("    {" + ", ".join(arr(offsets[e]) for e in range(nl)) + "},")
    L.append(f"    {pad_id}u")
    L.append("};")
    L.append("static_assert(kHashParams.offset[0][23] + (int64_t)kHashParams.prime[0][23] == kRows[0], \"layer 1 table rows\");")
    L.append("static_assert(kHashParams.offset[1][23] + (int64_t)kHashParams.prime[1][23] == kRows[1], \"layer 14 table rows\");")
    L.append("}}  // namespace ds41::engram")
    open(a.out_h, "w").write("\n".join(L) + "\n")
    print(f"cmap: {len(cmap)} ids -> {cvocab} compressed, pad {pad_id}, sha256 {sha}")
    print(f"rows: {rows}  (config {args.engram_num_embeddings})")

    # --- oracle vectors: official NgramHashState, prefill in one call and token by token (cache carries the window)
    if a.vectors:
        rng = np.random.default_rng(20251025)
        seqs = []
        seqs.append(np.array([0, 1, 2, 3, 4, 5, 129279, 128000, 100000, 2, 2, 2, 7], dtype=np.int64))  # specials, pad id, vocab edge
        seqs.append(np.array([5], dtype=np.int64))                                                   # one token (all lookbacks blocked)
        seqs.append(np.array([5, 6], dtype=np.int64))
        for n in (3, 4, 5, 17, 64, 513):
            seqs.append(rng.integers(0, len(cmap), size=n))
        seqs.append(rng.integers(0, 200, size=300))                                                  # many equal compressed ids
        seqs.append(rng.integers(0, len(cmap), size=2000))
        out = bytearray(b"G6EVEC01" + struct.pack("<I", len(seqs)))
        for s in seqs:
            st = E.NgramHashState(args, layout, tok)
            ids = st(torch.tensor(s, dtype=torch.long)[None], 0)[0]            # [L, nl, 24], one prefill call
            assert ids.shape == (len(s), nl, 24)
            st2 = E.NgramHashState(args, layout, tok)
            step = torch.cat([st2(torch.tensor([int(t)])[None], p)[0] for p, t in enumerate(s)])  # one token per call
            assert torch.equal(ids, step), "official prefill != official decode"
            assert int(ids.min()) >= 0 and int(ids.max()) < 2**32
            out += struct.pack("<I", len(s)) + s.astype("<i4").tobytes() + ids.numpy().astype("<u4").tobytes()
        open(a.vectors, "wb").write(out)
        print(f"vectors: {len(seqs)} sequences, {sum(len(s) for s in seqs)} tokens -> {a.vectors} ({len(out)} B)")


if __name__ == "__main__":
    main()
